import { splitEvoLines } from "./evo-text.js";

/*
  4x4 Evolution vehicle manifests: TRK version 6 (Evo 1) and version 7 (Evo 2).

    version
    6                                   6 = 4x4 Evolution, 7 = 4x4 Evolution 2
    truckName
    Chevrolet Blazer TrailBlazer 4WD
    ...
    signature: C89BC44E D3A8FB4D // WARNING: Do not edit this file

  It is the same line-oriented label/value text MTM2 uses, with a version header instead of
  an "MTM2" one, and three differences that matter to a reader:

    - Wheel anchors are ONE vec3 line ("faxle.rtire.static_bpos" -> "+2.385,-0.700,+5.360").
      MTM2 splits the same data into three ".x"/".y"/".z" label/value pairs.
    - Several fields are counted lists: a "<label>[]" line followed by N bare value lines.
      Where the count lives in an earlier field it is used; "sc[].pt" has no count anywhere,
      so its run is read until a line stops looking like a vec3, which is unambiguous because
      every label that can follow it is non-numeric.
    - "xm.gear_ratio[]" is the one list label carrying a trailing gear-name comment, and the
      comment changes with the gear count, so it is matched on everything up to the "[]".

  Verified against every manifest in both stock TRUCK.PODs: 121 v6 files and 150 v7 files,
  each read to its signature line with no list value mistaken for a label.

  Positions are in feet, the same unit MTM2 uses, so nothing here rescales.
*/

const EVO_VERSIONS = { 6: 1, 7: 2 };

const COUNTED_LISTS = {
  "xm.gear_ratio[]": "xm.maxGear",
  "xm.gearInertia[]": "xm.maxGear",
  "eng.torqueTable[]": "eng.torqueTableCount",
  "stockPartList[]": "numStockParts",
  "colorList[]": "numColors",
};

export const WHEEL_KEYS = [
  "faxle.rtire.static_bpos",
  "faxle.ltire.static_bpos",
  "raxle.rtire.static_bpos",
  "raxle.ltire.static_bpos",
];

const WHEEL_KEY_SET = new Set(WHEEL_KEYS);
const NAMED_STRINGS = new Set(["truckModelBaseName", "tireModelBaseName", "axleModelName", "shockTextureName", "barTextureName"]);
const TEXT_SPECS = new Set(["truckMake", "truckModel", "truckClass", "teamRequirement"]);

/** True when these lines open with the Evo "version" / 6|7 pair rather than an MTM header. */
export function isEvoTruckManifest(lines) {
  return (lines[0] ?? "").trim().toLowerCase() === "version" && Number.parseInt(lines[1] ?? "", 10) in EVO_VERSIONS;
}

export function parseEvoTruck(bytes, sourceName) {
  const lines = splitEvoLines(bytes).map(line => line.trim()).filter(line => line.length > 0);
  if (!isEvoTruckManifest(lines)) throw new Error(`${sourceName}: not an Evo TRK (expected a "version" header of 6 or 7)`);
  const version = Number.parseInt(lines[1], 10);
  const truck = {
    sourceName, version, game: EVO_VERSIONS[version],
    truckName: "", truckModelBaseName: "", tireModelBaseName: "", axleModelName: "",
    shockTextureName: "", barTextureName: "",
    wheelAnchors: {}, scrapePoints: [], lights: [], colors: [], stockParts: [],
    waveFiles: [], instrumentCluster: "", specs: {}, signature: "", warnings: [],
  };

  for (let i = 2; i < lines.length; i++) {
    const label = lines[i];
    if (label.startsWith("signature:")) { truck.signature = label.slice(10).split("//")[0].trim(); continue; }

    if (label === "sc[].pt") {
      while (i + 1 < lines.length && isVec3(lines[i + 1])) truck.scrapePoints.push(vec3(lines[++i]));
      continue;
    }

    const listLabel = label.includes("[]") ? label.slice(0, label.indexOf("[]") + 2) : label;
    const countField = COUNTED_LISTS[listLabel];
    if (countField) {
      const count = Math.max(0, Math.trunc(Number(truck.specs[countField]) || 0));
      const values = lines.slice(i + 1, i + 1 + count);
      i += values.length;
      if (listLabel === "colorList[]") truck.colors = values.map(colorEntry);
      else if (listLabel === "stockPartList[]") truck.stockParts = values.map(value => value.trim());
      else truck.specs[listLabel] = values.map(value => number(value));
      continue;
    }

    const value = lines[i + 1] ?? "";
    if (label === "Wave File") {
      truck.waveFiles.push(value); i++;
      while (i + 1 < lines.length && /\.wav$/i.test(lines[i + 1])) truck.waveFiles.push(lines[++i]);
      continue;
    }
    if (WHEEL_KEY_SET.has(label)) { truck.wheelAnchors[label] = vec3(value); i++; continue; }
    if (label === "truckName") { truck.truckName = value; i++; continue; }
    if (NAMED_STRINGS.has(label)) { truck[label] = value; i++; continue; }
    if (label === "Instrument Cluster") { truck.instrumentCluster = value; i++; continue; }
    if (label === "Number of Lights") { truck.specs.numberOfLights = Number.parseInt(value, 10) || 0; i++; continue; }

    const light = label.match(/^Light (\d+) /);
    if (light) { applyLight(truck, Number.parseInt(light[1], 10), label.slice(light[0].length).trim(), value); i++; continue; }

    truck.specs[label] = TEXT_SPECS.has(label) ? value : specValue(value);
    i++;
  }

  truck.lights = truck.lights.filter(Boolean);
  if (!truck.truckModelBaseName) truck.warnings.push(`${sourceName}: no truckModelBaseName; there is no body to convert.`);
  for (const key of WHEEL_KEYS) if (!truck.wheelAnchors[key]) truck.warnings.push(`${sourceName}: missing wheel anchor ${key}; it was placed at the origin.`);
  return truck;
}

function applyLight(truck, index, property, value) {
  while (truck.lights.length <= index) truck.lights.push(null);
  truck.lights[index] ??= { index };
  const light = truck.lights[index];
  const parts = value.split(",");
  if (property === "type") light.type = Number.parseInt(value, 10) || 0;
  else if (property.startsWith("body axis pos")) {
    light.pos = { x: number(parts[0]), y: number(parts[1]), z: number(parts[2]) };
    light.bitmapRadius = number(parts[3]);
  } else if (property.startsWith("heading")) {
    light.heading = number(parts[0]); light.pitch = number(parts[1]); light.spinSpeed = number(parts[2]);
  } else if (property.startsWith("cone:")) {
    light.coneLength = number(parts[0]); light.coneBaseRadius = number(parts[1]);
    light.coneRimRadius = number(parts[2]); light.coneTexture = (parts[3] ?? "").trim();
  } else if (property.startsWith("source:")) light.sourceBitmap = value.trim();
  else if (property.startsWith("ms on")) { light.msOn = Number.parseInt(parts[0], 10) || 0; light.msOff = Number.parseInt(parts[1], 10) || 0; }
}

/*
  A paint scheme: an HSV shift, the RGB swatch the Evo garage shows for it, and a decal
  texture. Every entry in both stock archives names "NULL" for that texture, so only the
  swatch is carried forward.
*/
function colorEntry(line) {
  const parts = line.split(",");
  return {
    hue: number(parts[0]), saturation: number(parts[1]), brightness: number(parts[2]),
    red: clampByte(parts[3]), green: clampByte(parts[4]), blue: clampByte(parts[5]),
    textureName: (parts[6] ?? "").trim(),
  };
}

function isVec3(line) { const p = line.split(","); return p.length === 3 && p.every(part => Number.isFinite(Number.parseFloat(part))); }
function vec3(value) { const p = String(value).split(","); return { x: number(p[0]), y: number(p[1]), z: number(p[2]) }; }
function number(value) { const n = Number.parseFloat(String(value ?? "").trim()); return Number.isFinite(n) ? n : 0; }
function clampByte(value) { return Math.max(0, Math.min(255, Math.round(number(value)))); }

// Scalars stay numbers and comma tuples become number arrays, so an unrecognised field still
// survives into the log in a usable shape rather than as raw text.
function specValue(value) {
  const trimmed = String(value).trim();
  if (!trimmed) return "";
  const parts = trimmed.split(",");
  if (parts.every(part => /^[+-]?(\d+\.?\d*|\.\d+)([eE][+-]?\d+)?$/.test(part.trim()))) {
    return parts.length === 1 ? number(parts[0]) : parts.map(number);
  }
  return trimmed;
}
